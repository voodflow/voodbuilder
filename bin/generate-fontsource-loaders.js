#!/usr/bin/env node
/**
 * Generate explicit Vite-friendly dynamic import map for core Fontsource fonts.
 * Uses ?inline so CSS is returned as a string (Rolldown/Vite may not leave
 * detectable <style>/<link> tags for side-effect CSS imports).
 *
 * Run: node packages/voodflow/voodbuilder/bin/generate-fontsource-loaders.js
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(readFileSync(join(root, 'resources/fonts/core-catalog.json'), 'utf8'));

const entries = [];

for (const font of catalog) {
    if (font.provider !== 'fontsource' || ! font.package) {
        continue;
    }

    const imports = (font.files ?? []).map(
        (file) => `import('${font.package}/${file}?inline')`,
    );

    if (imports.length === 0) {
        continue;
    }

    entries.push(
        `    ${JSON.stringify(font.id)}: async () => {\n`
        + `        const modules = await Promise.all([\n`
        + `            ${imports.join(',\n            ')},\n`
        + `        ]);\n`
        + `        return modules\n`
        + `            .map((mod) => (typeof mod === 'string' ? mod : (mod?.default ?? '')))\n`
        + `            .filter(Boolean)\n`
        + `            .join('\\n');\n`
        + `    }`,
    );
}

const out = `/**
 * AUTO-GENERATED by bin/generate-fontsource-loaders.js — do not edit by hand.
 * Each loader returns concatenated CSS text (?inline) for host + canvas injection.
 */
export const fontsourceLoaders = {
${entries.join(',\n')},
};
`;

const target = join(root, 'resources/js/editor/fonts/fontsource-loaders.js');
writeFileSync(target, out);
console.log(`Wrote ${entries.length} loaders → ${target}`);
