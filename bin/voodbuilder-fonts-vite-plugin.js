/**
 * Vite plugin: Fontsource publish entries + voodbuilder-fonts-manifest.json
 *
 * Core ships ~50 Fontsource fonts. Each gets a tiny JS entry that only imports
 * CSS so Vite emits hashed stylesheets. Published pages load only used fonts
 * via FontStylesheets::urlsFor() + the manifest.
 *
 * Plugins (Bunny, etc.) extend the editor catalog in JS/PHP; they can ship
 * their own publish assets and merge into the manifest at install time.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const catalogPath = join(packageRoot, 'resources/fonts/core-catalog.json');
const publishDir = join(packageRoot, 'resources/js/fonts/publish');

function loadCatalog() {
    try {
        const decoded = JSON.parse(readFileSync(catalogPath, 'utf8'));

        return Array.isArray(decoded) ? decoded : [];
    } catch {
        return [];
    }
}

/**
 * Ensure one Vite entry per fontsource font. Returns host-relative entry paths.
 *
 * @param {string} [projectRoot]
 * @returns {string[]}
 */
export function ensureFontPublishEntries(projectRoot = process.cwd()) {
    const catalog = loadCatalog();
    const entries = [];

    mkdirSync(publishDir, { recursive: true });

    for (const font of catalog) {
        if (font.provider !== 'fontsource' || ! font.package || ! font.id) {
            continue;
        }

        const files = Array.isArray(font.files) ? font.files : [];

        if (files.length === 0) {
            continue;
        }

        const imports = files
            .map((file) => `import '${font.package}/${file}';`)
            .join('\n');

        const fileName = `${font.id}.js`;
        const absolute = join(publishDir, fileName);

        writeFileSync(
            absolute,
            `/** AUTO-GENERATED by voodbuilder-fonts-vite-plugin — do not edit. */\n${imports}\n`,
        );

        entries.push(relative(projectRoot, absolute).replaceAll('\\', '/'));
    }

    return entries;
}

/**
 * Collect CSS files for a font publish entry.
 * Vite/Rolldown attaches CSS to imported weight chunks, not the entry itself.
 * Only walk one import level — deeper imports can point at the editor entry.
 *
 * @param {Record<string, any>} viteManifest
 * @param {string} entryKey
 * @returns {string[]}
 */
function collectCssFromEntry(viteManifest, entryKey) {
    const chunk = viteManifest[entryKey];

    if (! chunk || typeof chunk !== 'object') {
        return [];
    }

    const css = [];

    if (Array.isArray(chunk.css)) {
        css.push(...chunk.css.map(String));
    }

    for (const imported of chunk.imports ?? []) {
        const child = viteManifest[String(imported)];

        if (child && Array.isArray(child.css)) {
            css.push(...child.css.map(String));
        }
    }

    return css;
}

/**
 * Read Laravel Vite manifest and write id → CSS href map.
 *
 * @param {string} [projectRoot]
 */
export function writeFontsManifest(projectRoot = process.cwd()) {
    const viteManifestPath = join(projectRoot, 'public/build/manifest.json');
    const outPath = join(projectRoot, 'public/build/voodbuilder-fonts-manifest.json');
    const catalog = loadCatalog();
    const fontsManifest = {};

    let viteManifest = {};

    try {
        viteManifest = JSON.parse(readFileSync(viteManifestPath, 'utf8'));
    } catch {
        writeFileSync(outPath, '{}\n');

        return outPath;
    }

    for (const font of catalog) {
        if (font.provider !== 'fontsource' || ! font.id) {
            continue;
        }

        const entryKey = relative(projectRoot, join(publishDir, `${font.id}.js`)).replaceAll('\\', '/');

        if (! viteManifest[entryKey]) {
            continue;
        }

        const cssFiles = [...new Set(collectCssFromEntry(viteManifest, entryKey))];
        const hrefs = cssFiles
            .map((file) => `/build/${String(file).replace(/^\/+/, '')}`)
            .filter(Boolean);

        if (hrefs.length === 1) {
            fontsManifest[font.id] = hrefs[0];
        } else if (hrefs.length > 1) {
            fontsManifest[font.id] = hrefs;
        }
    }

    writeFileSync(outPath, `${JSON.stringify(fontsManifest, null, 2)}\n`);

    return outPath;
}

/**
 * @returns {import('vite').Plugin}
 */
export function voodbuilderFontsPlugin() {
    let projectRoot = process.cwd();

    return {
        name: 'voodbuilder-fonts-manifest',
        configResolved(config) {
            projectRoot = config.root || process.cwd();
            ensureFontPublishEntries(projectRoot);
        },
        /**
         * Prefer a short FOIT over FOUT on published pages: with woff2 preload,
         * block usually resolves before first paint; swap flashes the fallback.
         */
        transform(code, id) {
            const normalized = String(id).replaceAll('\\', '/');

            if (
                ! normalized.includes('@fontsource')
                || ! normalized.includes('.css')
                || ! code.includes('font-display')
            ) {
                return null;
            }

            const next = code.replace(/font-display\s*:\s*swap\b/gi, 'font-display:block');

            return next === code ? null : next;
        },
        closeBundle() {
            writeFontsManifest(projectRoot);
        },
    };
}
